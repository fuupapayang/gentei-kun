#!/usr/bin/env node
/* Writes firestore.rules from firestore.rules.template with the admin e-mails injected.
 *   node scripts/make-rules.js admin1@example.com,admin2@example.com     (or env ADMIN_EMAILS)
 * No e-mails => admin list is empty (nobody has admin rights). */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
const raw = process.argv[2] !== undefined ? process.argv[2] : process.env.ADMIN_EMAILS || '';
const emails = [...new Set(raw.split(/[,\s]+/).map(s => s.trim().toLowerCase()).filter(Boolean))];
for (const e of emails) if (!/^[^\s@'"\\]+@[^\s@'"\\]+\.[^\s@'"\\]+$/.test(e)) { console.error('ERROR: invalid admin e-mail: ' + e); process.exit(1); }
if (!emails.length) console.warn('WARN: no admin e-mails given: firestore.rules will grant NO admin access.');
const tpl = fs.readFileSync(path.join(ROOT, 'firestore.rules.template'), 'utf8');
if (!tpl.includes('__ADMIN_EMAILS__')) { console.error('ERROR: placeholder __ADMIN_EMAILS__ missing in template'); process.exit(1); }
const body = tpl.replace(/__ADMIN_EMAILS__/g, '[' + emails.map(e => "'" + e + "'").join(', ') + ']');
const out = body.replace(/^(rules_version[^\n]*\n)/m, '$1// GENERATED by scripts/make-rules.js from firestore.rules.template - do not edit by hand.\n');
fs.writeFileSync(path.join(ROOT, 'firestore.rules'), out);
console.log('wrote firestore.rules  admins=' + emails.length + (emails.length ? ' (' + emails.join(', ') + ')' : ''));
